import {chromium} from 'playwright-core';
import {resolve} from 'node:path';

const executablePath=process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe';
const browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('button',{name:/새 게임 시작/}).click();
await page.locator('input[type="range"]').focus();
await page.keyboard.press('End');
await page.getByRole('button',{name:/게임 시작!|Start Game!/}).click();
await page.waitForTimeout(400);
await page.screenshot({path:resolve('screenshot-board.png')});
await page.locator('.question-tile:not([disabled])').first().click();
await page.locator('.question-card').waitFor();
await page.waitForTimeout(500);
await page.screenshot({path:resolve('screenshot-question.png')});
page.once('dialog',dialog=>dialog.accept());
await page.getByRole('button',{name:/객관식 전환/}).click();
const points=await page.locator('.points-badge').innerText();
if(!points.includes('10'))throw Error(`Multiple choice scoring failed: ${points}`);
await page.getByRole('button',{name:/정답!|Correct!/}).click();
await page.locator('.chest-grid button:not([disabled])').first().click();
await page.screenshot({path:resolve('screenshot-bonus.png')});
await page.reload();
if(!(await page.locator('.bonus-view').count()))throw Error('Refresh did not restore bonus screen');
if(errors.length)throw Error(errors.join('\n'));
console.log('Browser flow passed: start → question → multiple choice → correct → box → refresh.');
await browser.close();
