import {chromium} from 'playwright-core';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('button',{name:/새 게임 시작/}).click();
await page.getByRole('button',{name:/게임 시작!|Start Game!/}).click();
await page.waitForTimeout(400);
await page.screenshot({path:'screenshot-board-with-songs.png'});
const songTiles=await page.locator('.category-col').last().locator('.question-tile').allInnerTexts();
if(!songTiles[0].includes('200')||!songTiles[1].includes('250')||!songTiles[2].includes('200')||!songTiles[3].includes('200'))throw Error(`Song board points are incorrect: ${songTiles.join(', ')}`);
await page.locator('.category-col').last().locator('.question-tile').first().click();
await page.locator('.audio-box').waitFor();
if(!(await page.locator('.timer').innerText()).includes('30s'))throw Error('Song timer is not 30 seconds');
if(await page.getByRole('button',{name:/객관식 전환/}).count())throw Error('Multiple choice is visible for a song');
const duration=await page.locator('audio').evaluate(async a=>{await new Promise(r=>{if(a.readyState>=1)r();else a.addEventListener('loadedmetadata',r,{once:true})});return a.duration});
if(Math.abs(duration-8)>0.1)throw Error(`Preview duration is ${duration}`);
await page.getByRole('button',{name:/계속 듣기/}).click();
await page.waitForTimeout(400);
const current=await page.locator('audio').evaluate(a=>a.currentTime);
if(current<7.8)throw Error(`Continuation did not seek to the cutoff: ${current}`);
await page.getByRole('button',{name:/제목은 기억 안 나지만/}).click();
if(!(await page.getByRole('button',{name:/한 소절 인정/}).count()))throw Error('Sing-a-line chance did not activate');
if(errors.length)throw Error(errors.join('\n'));
console.log('Song flow passed: 30-second timer, 8-second preview, continuation, subjective sing-a-line chance.');
await browser.close();
